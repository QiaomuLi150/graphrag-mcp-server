def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def _entity(kind: str, name: str, aliases: list[str] | None = None, description: str | None = None) -> dict[str, Any]:
    return {
        "id": f"{KIND_PREFIX[kind]}-{slug(name)}",
        "name": name,
        "kind": kind,
        "description": description or KIND_DESCRIPTION[kind],
        "aliases": sorted(set(aliases or [])),
    }


def generate() -> dict[str, list[dict[str, Any]]]:
    rng = random.Random(SEED)  # noqa: S311 - deterministic synthetic data, not security

    entities: dict[str, dict[str, Any]] = {}

    def add(e: dict[str, Any]) -> dict[str, Any]:
        assert e["id"] not in entities, f"duplicate id {e['id']}"
        entities[e["id"]] = e
        return e

    teams = [add(_entity("Team", f"{n} Team", [n])) for n in TEAM_NAMES]
    products = [add(_entity("Product", n)) for n in PRODUCT_NAMES]

    # Services: 45 unique "<Domain> <Role>" names, deterministic sample.
    combos = [(d, r) for d in DOMAINS for r in ROLES if (d, r) != ("Ledger", "Service")]
    rng.shuffle(combos)
    services: list[dict[str, Any]] = []
    for d, r in combos[:45]:
        name = f"{d} {r}"
        aliases = [f"{d.lower()}-{r.lower()}", f"{d}{r}"]
        services.append(add(_entity("Service", name, aliases)))

    # Deliberate ambiguity fixture: two services share the alias "Gateway".
    for nm in ("Edge Gateway Service", "Partner Gateway Service"):
        services.append(add(_entity("Service", nm, ["Gateway"])))
    # Unique short alias fixture.
    services.append(add(_entity("Service", "Ledger Service", ["Ledger"])))

    stores = []
    for i, d in enumerate(STORE_DOMAINS):
        kind_name = STORE_KINDS[i % len(STORE_KINDS)]
        stores.append(add(_entity("Datastore", f"{d} {kind_name}", [f"{d} store"])))
    libs = [add(_entity("Library", n)) for n in LIBRARIES]
    queues = [add(_entity("Queue", f"{n} Queue")) for n in QUEUES]
    features = [add(_entity("Feature", n)) for n in FEATURES]

    # --- Isolated island (guaranteed unreachable from the main component) ---
    island = [
        add(_entity("Service", "Legacy Archive Tool", ["archive-tool"])),
        add(_entity("Datastore", "Cold Archive Tape Store")),
        add(_entity("Team", "Archive Maintenance Team")),
    ]

    edges: dict[tuple[str, str, str], dict[str, Any]] = {}

    def rel(rtype: str, a: dict[str, Any], b: dict[str, Any]) -> None:
        if a["id"] == b["id"]:
            return
        edges.setdefault((rtype, a["id"], b["id"]), {"type": rtype, "source": a["id"], "target": b["id"]})

    # Ownership: every service / store / library / queue has exactly one owning team.
    main_assets = services + stores + libs + queues
    for i, asset in enumerate(main_assets):
        rel("OWNS", teams[(i * 7 + rng.randrange(len(teams))) % len(teams)], asset)
    # Features belong to a product and are implemented by 1-2 services.
    for i, f in enumerate(features):
        rel("PART_OF", f, products[i % len(products)])
        for s in rng.sample(services, rng.choice([1, 2])):
            rel("IMPLEMENTED_BY", f, s)
    # Service dependency structure: layered to keep the graph a realistic, sparse DAG-ish web.
    for i, s in enumerate(services):
        later = services[i + 1 :]
        for t in rng.sample(later, min(len(later), rng.choice([1, 2, 3]))):
            rel("DEPENDS_ON", s, t)
        rel("DEPENDS_ON", s, rng.choice(stores))
        for lib in rng.sample(libs, rng.choice([1, 2, 3])):
            rel("USES", s, lib)
        if rng.random() < 0.45:
            rel("PUBLISHES_TO", s, rng.choice(queues))
        if rng.random() < 0.45:
            rel("CONSUMES_FROM", s, rng.choice(queues))
        if rng.random() < 0.15 and later:
            rel("INTEGRATES_WITH", s, rng.choice(later))
    # Island wiring (disconnected from everything above).
    rel("OWNS", island[2], island[0])
    rel("OWNS", island[2], island[1])
    rel("DEPENDS_ON", island[0], island[1])

    ent_list = sorted(entities.values(), key=lambda e: e["id"])
    edge_list = []
    for key in sorted(edges, key=lambda k: (k[1], k[0], k[2])):
        e = dict(edges[key])
        e["id"] = "e-" + hashlib.sha1("|".join(key).encode(), usedforsecurity=False).hexdigest()[:12]  # noqa: S324 - id only
        edge_list.append(e)

    # Evidence: group facts into chunks of 5, chunks into sources of 4.
    # Island facts are kept together in their own source so they stay a coherent evidence unit.
    island_ids = {e["id"] for e in island}
    main_edges = [e for e in edge_list if e["source"] not in island_ids and e["target"] not in island_ids]
    isl_edges = [e for e in edge_list if e["source"] in island_ids or e["target"] in island_ids]

    sources: list[dict[str, Any]] = []
    chunks: list[dict[str, Any]] = []
    name_of = {e["id"]: e["name"] for e in ent_list}
    doc_titles = [f"{p} Architecture Overview" for p in PRODUCT_NAMES] + [f"{t} Team Handbook" for t in TEAM_NAMES]

    def emit(group: list[dict[str, Any]], src_id: str) -> None:
        cid = f"ch-{len(chunks) + 1:04d}"
        sentences = []
        for e in group:
            stmt = REL_STATEMENT[e["type"]].format(a=name_of[e["source"]], b=name_of[e["target"]])
            e["statement"] = stmt
            e["chunk_id"] = cid
            e["source_id"] = src_id
            e["confidence"] = 1.0
            sentences.append(stmt)
        mentions = sorted({x for e in group for x in (e["source"], e["target"])})
        chunks.append({"id": cid, "source_id": src_id, "text": " ".join(sentences), "mentions": mentions})

    chunk_groups = [main_edges[i : i + 5] for i in range(0, len(main_edges), 5)]
    n_src = max(1, (len(chunk_groups) + 3) // 4)
    for si in range(n_src):
        sid = f"src-{si + 1:03d}"
        sources.append(
            {
                "id": sid,
                "title": doc_titles[si % len(doc_titles)]
                + (f" (part {si // len(doc_titles) + 1})" if si >= len(doc_titles) else ""),
                "uri": f"demo://docs/{sid}",
                "license": LICENSE,
            }
        )
        for g in chunk_groups[si * 4 : (si + 1) * 4]:
            emit(g, sid)
    sid = f"src-{n_src + 1:03d}"
    sources.append({"id": sid, "title": "Archive Maintenance Notes", "uri": f"demo://docs/{sid}", "license": LICENSE})
    emit(isl_edges, sid)

    # Entity evidence = chunks that mention it.
    mention_idx: dict[str, list[str]] = {}
    for c in chunks:
        for m in c["mentions"]:
            mention_idx.setdefault(m, []).append(c["id"])
    for e in ent_list:
        e["evidence_chunks"] = mention_idx.get(e["id"], [])

    return {"nodes": ent_list, "edges": edge_list, "sources": sources, "chunks": chunks}


def _dump_jsonl(path: Path, rows: list[dict[str, Any]]) -> str:
    text = "".join(json.dumps(r, sort_keys=True, ensure_ascii=False) + "\n" for r in rows)
    path.write_text(text, encoding="utf-8")
    return hashlib.sha256(text.encode()).hexdigest()


def write(out: Path) -> dict[str, Any]:
    out.mkdir(parents=True, exist_ok=True)
    data = generate()
    checks = {n: _dump_jsonl(out / f"{n}.jsonl", rows) for n, rows in data.items()}
    revision = hashlib.sha256("".join(f"{k}:{v}" for k, v in sorted(checks.items())).encode()).hexdigest()[:16]
    manifest = {
        "dataset": "graphrag-mcp-demo",
        "generator_version": GENERATOR_VERSION,
        "seed": SEED,
        "license": LICENSE,
        "synthetic": True,
        "counts": {n: len(rows) for n, rows in data.items()},
        "sha256": checks,
        "graph_revision": f"demo-{revision}",
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/demo")
    args = ap.parse_args()
    m = write(Path(args.out))
    print(json.dumps(m["counts"]), m["graph_revision"])


if __name__ == "__main__":
    main()
