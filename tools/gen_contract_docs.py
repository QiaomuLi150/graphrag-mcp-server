"""Generate docs/TOOL_CONTRACTS.md from a RUNNING server so every example is real output.

GRAPHRAG_SMOKE_TOKEN=... python -m tools.gen_contract_docs --url http://127.0.0.1:28080/mcp
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
from pathlib import Path

from fastmcp import Client
from fastmcp.exceptions import ToolError

EXAMPLES = [
    ("search_entities", {"query": "ledger service", "labels": ["Service"], "limit": 2}),
    ("get_entity", {"entity_id": "svc-ledger-service", "neighbor_limit": 2}),
    (
        "find_relationship_paths",
        {
            "source_entity_id": "feat-gift-cards",
            "target_entity_id": "svc-ledger-service",
            "max_hops": 3,
            "max_paths": 1,
        },
    ),
    (
        "retrieve_graph_context",
        {"query": "How is Partner Gateway Service related to Ledger Service?", "top_k": 2, "max_chars": 700},
    ),
]
ERRORS = [
    ("get_entity", {"entity_id": "svc-does-not-exist"}),
    (
        "find_relationship_paths",
        {"source_entity_id": "svc-ledger-service", "target_entity_id": "feat-gift-cards", "max_hops": 9},
    ),
]


def j(x: object) -> str:
    return "```json\n" + json.dumps(x, indent=2, ensure_ascii=False) + "\n```\n"


async def main_async(url: str, token: str) -> str:
    out = [
        "# Tool contracts (v1.0)\n",
        "Generated by `tools/gen_contract_docs.py` from a live server: every example below is real output "
        "(request ids/latency are instance-specific). Contract version is returned in `meta.contract_version`; "
        "an incompatible change bumps the major version and ships under new tool names.\n",
        "All tools are read-only (`readOnlyHint: true`), require scope `graph:read`, and are bounded: "
        "list sizes, hop counts, character budgets and response bytes are capped server-side. "
        "Errors are returned as MCP tool errors whose text is the JSON `ToolError` object "
        "`{code, message, retryable, request_id}`; transport/auth failures are HTTP 401/403.\n",
        "Error codes: `INVALID_ARGUMENT`, `UNAUTHENTICATED`, `PERMISSION_DENIED`, `NOT_FOUND`, `RATE_LIMITED`, "
        "`TIMEOUT`, `DB_UNAVAILABLE`, `INSUFFICIENT_EVIDENCE` (reserved: absence of evidence is reported via "
        "`sufficient_evidence=false`, not an error), `INTERNAL_ERROR`.\n",
    ]
    async with Client(url, auth=token) as c:
        tools = {t.name: t for t in await c.list_tools()}
        for name, args in EXAMPLES:
            t = tools[name]
            res = (await c.call_tool(name, args)).structured_content
            out += [
                f"\n## `{name}`\n",
                f"{t.description}\n",
                "**Input schema**\n",
                j(t.input_schema),
                "**Example request**\n",
                j(args),
                "**Example response**\n",
                j(res),
            ]
        out.append("\n## Example errors\n")
        for ename, eargs in ERRORS:
            try:
                await c.call_tool(ename, eargs)
            except ToolError as e:
                out += [f"`{ename}` with `{json.dumps(eargs)}`:\n", j(json.loads(str(e)))]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", required=True)
    ap.add_argument("--out", default="docs/TOOL_CONTRACTS.md")
    a = ap.parse_args()
    Path(a.out).write_text(asyncio.run(main_async(a.url, os.environ["GRAPHRAG_SMOKE_TOKEN"])))


if __name__ == "__main__":
    main()
